#!/usr/bin/env python3
"""
generate_platform_profiles_cs.py

PROJECT XINGSHU HS4-A.2: Build-time code generator for XingShu Platform Profiles in C#.
Reads the canonical source of truth JSON file and generates a strongly-typed, auto-generated
C# constant class `PlatformProfilesGenerated` containing CANONICAL_PROFILES_JSON.
"""

import argparse
import json
import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.abspath(os.path.join(script_dir, "..", ".."))

    default_json = os.path.join(
        repo_root, "AstralParty-Hub", "src-tauri", "src", "xing_shu", "platform", "platform_profiles.json"
    )
    default_output = os.path.join(
        repo_root, "XingShu-Dev", "src", "XingShu.Runtime", "XingShu", "Platform", "PlatformProfiles.Generated.cs"
    )

    parser = argparse.ArgumentParser(description="Generate PlatformProfiles.Generated.cs from canonical JSON")
    parser.add_argument("--json", default=default_json, help="Path to platform_profiles.json")
    parser.add_argument("--output", default=default_output, help="Path to output PlatformProfiles.Generated.cs")
    args = parser.parse_args()

    json_path = os.path.abspath(args.json)
    output_path = os.path.abspath(args.output)

    if not os.path.isfile(json_path):
        print(f"[ERROR] Canonical JSON file not found: {json_path}", file=sys.stderr)
        sys.exit(1)

    with open(json_path, "r", encoding="utf-8") as f:
        raw_json = f.read()

    # Validate JSON syntax
    try:
        parsed = json.loads(raw_json)
        if not isinstance(parsed, list):
            raise ValueError(f"Expected JSON root to be a list, got {type(parsed).__name__}")
    except Exception as e:
        print(f"[ERROR] Invalid canonical JSON in {json_path}: {e}", file=sys.stderr)
        sys.exit(1)

    # Escape quotes for C# verbatim string literal (@"...")
    # Normalizing line endings to \r\n for Windows C# source files
    normalized_json = raw_json.strip().replace("\r\n", "\n").replace("\n", "\r\n")
    escaped_json = normalized_json.replace('"', '""')

    cs_content = f"""// <auto-generated>
// AUTO-GENERATED — DO NOT EDIT
// Generated from AstralParty-Hub/src-tauri/src/xing_shu/platform/platform_profiles.json
// </auto-generated>

namespace XingShu.Platform
{{
    public static class PlatformProfilesGenerated
    {{
        public const string CANONICAL_PROFILES_JSON = @"{escaped_json}";
    }}
}}
"""

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, "w", encoding="utf-8", newline="") as f:
        f.write(cs_content)

    print(f"[SUCCESS] Generated {output_path} from {json_path} ({len(parsed)} profiles)")

if __name__ == "__main__":
    main()
