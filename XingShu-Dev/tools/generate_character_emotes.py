#!/usr/bin/env python3
"""
Generate static character emote registry for XingShu.Runtime from AstralParty-Hub catalog.
Matches pickStaticEmoteAsset() semantics in AstralParty-Hub/src/shared/gameLibrary.ts:
- Excludes preview characters (`preview` truthy or empty trimmed name)
- Includes only non-animated emotes with non-empty image keys present in catalog.assets
- Picks deterministically per runtime session using a session salt + FNV-1a mix of heroId:slot
"""

import argparse
import json
import os
import sys


def escape_cs_string(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
    )


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.abspath(os.path.join(script_dir, "..", ".."))
    default_catalog = os.path.join(
        repo_root, "AstralParty-Hub", "src", "shared", "gameCatalog.generated.json"
    )
    default_output = os.path.join(
        repo_root,
        "XingShu-Dev",
        "src",
        "XingShu.Runtime",
        "XingShu",
        "Cards",
        "CharacterEmoteRegistry.Generated.cs",
    )

    parser = argparse.ArgumentParser(
        description="Generate CharacterEmoteRegistry.Generated.cs from gameCatalog.generated.json"
    )
    parser.add_argument("--catalog", default=default_catalog)
    parser.add_argument("--output", default=default_output)
    args = parser.parse_args()

    if not os.path.isfile(args.catalog):
        print(f"[ERROR] Catalog not found: {args.catalog}", file=sys.stderr)
        sys.exit(1)

    with open(args.catalog, "r", encoding="utf-8") as f:
        catalog = json.load(f)

    assets = catalog.get("assets") or {}
    characters = sorted(catalog.get("characters") or [], key=lambda c: int(c["id"]))

    entries = []
    for ch in characters:
        name = (ch.get("name") or "").strip()
        if ch.get("preview") or not name:
            continue
        emotes = []
        for emote in ch.get("emotes") or []:
            if emote.get("animated"):
                continue
            image = emote.get("image") or ""
            if image and assets.get(image):
                emotes.append(image)
        if emotes:
            entries.append((int(ch["id"]), name, emotes))

    lines = [
        "// <auto-generated>",
        "// AUTO-GENERATED BY generate_character_emotes.py — DO NOT EDIT",
        f"// Source: AstralParty-Hub/src/shared/gameCatalog.generated.json ({len(entries)} characters)",
        "// </auto-generated>",
        "",
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "",
        "namespace XingShu.Cards",
        "{",
        "    internal static class CharacterEmoteRegistry",
        "    {",
        "        private static readonly string[] Empty = new string[0];",
        "        private static readonly int SessionEmoteSalt = new Random().Next(0, int.MaxValue);",
        "",
        f"        private static readonly Dictionary<int, string[]> StaticEmotes = new Dictionary<int, string[]>({len(entries)})",
        "        {",
    ]

    for hero_id, name, emotes in entries:
        quoted = ", ".join(f'"{escape_cs_string(img)}"' for img in emotes)
        lines.append(f"            // {name}")
        lines.append(f"            {{ {hero_id}, new[] {{ {quoted} }} }},")

    lines.extend([
        "        };",
        "",
        "        internal static string[] GetStaticEmotes(int heroId)",
        "        {",
        "            return StaticEmotes.TryGetValue(heroId, out var emotes) ? emotes : Empty;",
        "        }",
        "",
        "        internal static string PickStaticEmote(int heroId, int slot = 0)",
        "        {",
        "            if (!StaticEmotes.TryGetValue(heroId, out var pool) || pool == null || pool.Length == 0)",
        "            {",
        "                return string.Empty;",
        "            }",
        '            string seed = heroId.ToString(CultureInfo.InvariantCulture) + ":" + slot.ToString(CultureInfo.InvariantCulture);',
        "            uint hash = unchecked((uint)SessionEmoteSalt ^ ((uint)heroId * 2654435761u));",
        "            for (int i = 0; i < seed.Length; i++)",
        "            {",
        "                hash = unchecked((hash ^ seed[i]) * 16777619u);",
        "            }",
        "            return pool[(int)(hash % (uint)pool.Length)];",
        "        }",
        "    }",
        "}",
        "",
    ])

    content = "\r\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    if os.path.isfile(args.output):
        with open(args.output, "r", encoding="utf-8") as f:
            if f.read() == content:
                print(f"CharacterEmoteRegistry up-to-date ({len(entries)} characters)")
                return
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {args.output} ({len(entries)} characters)")


if __name__ == "__main__":
    main()
