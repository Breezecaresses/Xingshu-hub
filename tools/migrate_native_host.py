"""Extract the desktop-independent command surface, retaining the web build feature."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
src = root / 'AstralParty-Hub/src-tauri/src'
backup = root / 'XingShu-Dev/build/native-windows/before'

def save(path, text):
    old = backup / path.relative_to(root)
    if not old.exists():
        old.parent.mkdir(parents=True, exist_ok=True)
        old.write_bytes(path.read_bytes())
    path.write_text(text, encoding='utf-8')

for path in src.rglob('*.rs'):
    if path.name in ('lib.rs', 'desktop_host.rs') or 'bin' in path.parts:
        continue
    text = path.read_text(encoding='utf-8-sig')
    if 'tauri::' not in text:
        continue
    text = text.replace('#[tauri::command]', '#[cfg_attr(feature = "web-ui", tauri::command)]')
    for item in ('State', 'AppHandle', 'Emitter'):
        text = text.replace('tauri::' + item, 'crate::desktop_host::' + item)
    text = text.replace('tauri::async_runtime::', 'crate::desktop_host::')
    save(path, text)

path = src / 'lib.rs'
text = path.read_text(encoding='utf-8-sig')
if 'mod web_host {' not in text:
    cut = text.index('use std::sync::Arc;')
    text = text[:cut] + 'pub mod desktop_host;\n\n#[cfg(feature = "web-ui")]\nmod web_host {\nuse super::*;\n' + text[cut:] + '\n}\n#[cfg(feature = "web-ui")]\npub use web_host::run;\n'
    save(path, text)

path = src.parent / 'Cargo.toml'
text = path.read_text(encoding='utf-8-sig')
if '[features]' not in text:
    text += '\n[features]\ndefault = ["web-ui"]\nweb-ui = ["dep:tauri", "dep:tauri-plugin-opener", "dep:tauri-build"]\nnative-backend = []\n\n[[bin]]\nname = "xingshu-hub"\npath = "src/main.rs"\nrequired-features = ["web-ui"]\n\n[[bin]]\nname = "xingshu-core"\npath = "src/bin/xingshu-core.rs"\nrequired-features = ["native-backend"]\n'
    text = text.replace('tauri-build = { version = "2", features = [] }', 'tauri-build = { version = "2", features = [], optional = true }')
    text = text.replace('tauri = { version = "2", features = [] }', 'tauri = { version = "2", features = [], optional = true }')
    text = text.replace('tauri-plugin-opener = "2"', 'tauri-plugin-opener = { version = "2", optional = true }')
    save(path, text)
path = src.parent / 'build.rs'
text = path.read_text(encoding='utf-8-sig').replace('    tauri_build::build()', '    #[cfg(feature = "web-ui")]\n    tauri_build::build()')
save(path, text)

# The protocol dispatcher is generated from the same command signatures as the old UI.
# Runtime arguments remain strongly deserialized; no arbitrary process / file commands.
fields = {
    'CatalogService':'catalog_service', 'DiagnosticService':'diagnostic_service',
    'ExtensionService':'extension_service','GameService':'game_service',
    'InstallService':'install_service','PlayerService':'player_service',
    'ProviderOrchestrator':'orchestrator', 'LocalWatcher':'watcher',
    'ExtensionCenter':'center','GameLibraryStore':'store',
    'Arc<BridgeServer>':'bridge_server','Arc<SpectatorService>':'spectator_service',
    'Arc<XingShuPackageManager>':'package_mgr','StartupLocale':'locale_state','StartupRoute':'route_state'
}
arms=[]
names=[]
for path in [*src.joinpath('commands').glob('*.rs'), src/'game_library.rs',src/'extension_center.rs']:
    text=path.read_text(encoding='utf-8-sig')
    for match in re.finditer(r'#\[cfg_attr\(feature = "web-ui", tauri::command\)\]\s*pub\s+(async\s+)?fn\s+(\w+)\s*\((.*?)\)\s*->\s*([^\{]+)',text,re.S):
        asynchronous,name,params,ret=match.groups()
        args=[]
        # Split parameters only at the top-level generic nesting depth.
        parts=[]; depth=0; start=0
        for i,c in enumerate(params):
            if c=='<': depth+=1
            elif c=='>': depth-=1
            elif c==',' and depth==0: parts.append(params[start:i]);start=i+1
        parts.append(params[start:])
        for part in parts:
            if not part.strip(): continue
            param,typ=part.split(':',1);param=param.strip();typ=typ.strip()
            if 'State<' in typ:
                typ=re.sub(r".*State<\s*(?:'_\s*,\s*)?",'',typ,count=1)[:-1].strip()
                typ=typ.removeprefix('crate::extension_center::')
                args.append('State::new(&self.'+fields[typ]+')')
            else:
                key=re.sub(r'_([a-z])',lambda m:m[1].upper(),param)
                args.append('arg(&args, "'+key+'")?')
        module='commands' if path.parent.name=='commands' else path.stem
        call=f'{module}::{name}('+', '.join(args)+')'+('.await' if asynchronous else '')
        if 'Result<' in ret: call += '.map_err(|e| e.to_string())?'
        arms.append(f'            "{name}" => value({call}),')
        names.append(name)
out=src/'native_dispatch.generated.rs'
out.write_text('// Generated by tools/migrate_native_host.py; shared typed command surface.\nimpl Core {\n    async fn dispatch(&self, command: &str, args: Value) -> Result<Value, String> {\n        match command {\n'+ '\n'.join(arms)+'\n            _ => Err(format!("未知命令: {}", command)),\n        }\n    }\n}\n' + 'const COMMANDS: &[&str] = &'+repr(names).replace("'",'"')+';\n',encoding='utf-8')
print(f'Native command surface: {len(names)} commands; original shared files backed up.')
